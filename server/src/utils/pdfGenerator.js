import PDFDocument from 'pdfkit';

/**
 * Generates a clean, ATS-compliant printable PDF document from resume data
 * @param {object} resume - Structured resume data (fullName, contact, professionalSummary, sections)
 * @returns {Promise<Buffer>}
 */
export async function generateResumePdf(resume) {
  if (!resume || typeof resume !== 'object') {
    throw new Error('Invalid resume data provided for PDF generation.');
  }

  const fullName = typeof resume.fullName === 'string' && resume.fullName.trim() ? resume.fullName.trim() : 'Resume';
  const professionalSummary = typeof resume.professionalSummary === 'string' ? resume.professionalSummary.trim() : '';
  const sections = Array.isArray(resume.sections) ? resume.sections : [];

  // Defensive contact resolution: handles null, undefined, or malformed contact objects
  const safeContact = resume.contact && typeof resume.contact === 'object' ? resume.contact : {};

  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        margin: 45,
        size: 'A4',
        bufferPages: true,
        info: {
          Title: `${fullName} - Resume`,
          Author: fullName,
          Subject: 'Professional Resume generated by ResumeAI',
        },
      });

      const chunks = [];
      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => {
        const resultBuffer = Buffer.concat(chunks);
        resolve(resultBuffer);
      });
      doc.on('error', (err) => reject(err));

      const primaryColor = '#111827'; // Dark charcoal
      const mutedColor = '#4b5563';   // Slate gray
      const dividerColor = '#d1d5db'; // Border line gray

      // 1. Header: Full Name
      doc
        .font('Helvetica-Bold')
        .fontSize(22)
        .fillColor(primaryColor)
        .text(fullName, { align: 'left' });

      doc.moveDown(0.25);

      // 2. Contact details line
      const contactPieces = [];
      if (typeof safeContact.email === 'string' && safeContact.email) contactPieces.push(safeContact.email);
      if (typeof safeContact.phone === 'string' && safeContact.phone) contactPieces.push(safeContact.phone);
      if (typeof safeContact.location === 'string' && safeContact.location) contactPieces.push(safeContact.location);
      if (typeof safeContact.linkedin === 'string' && safeContact.linkedin) {
        contactPieces.push(safeContact.linkedin.replace(/^https?:\/\/(www\.)?/i, ''));
      }
      if (typeof safeContact.github === 'string' && safeContact.github) {
        contactPieces.push(safeContact.github.replace(/^https?:\/\/(www\.)?/i, ''));
      }
      if (typeof safeContact.portfolio === 'string' && safeContact.portfolio) {
        contactPieces.push(safeContact.portfolio.replace(/^https?:\/\/(www\.)?/i, ''));
      }

      if (contactPieces.length > 0) {
        doc
          .font('Helvetica')
          .fontSize(9)
          .fillColor(mutedColor)
          .text(contactPieces.join('  •  '), { align: 'left' });
      }

      doc.moveDown(0.6);

      // Helper function to draw section headers
      const renderSectionHeading = (title) => {
        doc.moveDown(0.7);
        doc
          .font('Helvetica-Bold')
          .fontSize(11)
          .fillColor(primaryColor)
          .text(title.toUpperCase(), { characterSpacing: 0.5 });

        const y = doc.y + 2;
        doc
          .strokeColor(dividerColor)
          .lineWidth(0.75)
          .moveTo(doc.page.margins.left, y)
          .lineTo(doc.page.width - doc.page.margins.right, y)
          .stroke();

        doc.moveDown(0.5);
      };

      // 3. Professional Summary
      if (professionalSummary) {
        renderSectionHeading('Professional Summary');
        doc
          .font('Helvetica')
          .fontSize(9.5)
          .fillColor('#1f2937')
          .text(professionalSummary, {
            lineGap: 2.5,
            align: 'justify',
          });
      }

      // 4. Custom Sections (Skills, Experience, Projects, Education, etc.)
      for (const sec of sections) {
        if (!sec || !sec.heading || !Array.isArray(sec.items) || sec.items.length === 0) {
          continue;
        }

        renderSectionHeading(sec.heading);

        for (const item of sec.items) {
          if (!item) continue;
          const trimmedItem = String(item).trim();
          if (trimmedItem === '') continue;

          // Check if item looks like a sub-heading or role line
          const isRoleOrHeader =
            (trimmedItem.includes('|') || trimmedItem.includes('—') || trimmedItem.includes(' - ')) &&
            trimmedItem.length < 90 &&
            !trimmedItem.startsWith('•') &&
            !trimmedItem.startsWith('-');

          if (isRoleOrHeader) {
            doc.moveDown(0.2);
            doc
              .font('Helvetica-Bold')
              .fontSize(9.5)
              .fillColor(primaryColor)
              .text(trimmedItem, { lineGap: 1.5 });
            doc.font('Helvetica');
          } else {
            const cleanBulletText = trimmedItem.replace(/^[•\-*]\s*/, '');
            doc
              .font('Helvetica')
              .fontSize(9.5)
              .fillColor('#374151')
              .text(`•  ${cleanBulletText}`, {
                indent: 10,
                lineGap: 2,
                paragraphGap: 3.5,
              });
          }
        }
      }

      // 5. Add footer / page numbers if multiple pages
      const range = doc.bufferedPageRange();
      if (range.count > 1) {
        for (let i = 0; i < range.count; i++) {
          doc.switchToPage(i);
          doc
            .font('Helvetica')
            .fontSize(8)
            .fillColor('#9ca3af')
            .text(
              `${fullName}  |  Page ${i + 1} of ${range.count}`,
              doc.page.margins.left,
              doc.page.height - 30,
              {
                align: 'center',
                width: doc.page.width - doc.page.margins.left - doc.page.margins.right,
              }
            );
        }
      }

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

/**
 * Generates an A4 PDF for builder resume supporting Modern, Professional, and Minimal ATS templates
 * @param {object} params
 * @param {object} params.resumeData - Full builder state
 * @param {'modern'|'professional'|'ats'} [params.templateId='modern']
 * @param {object} [params.customization]
 * @returns {Promise<Buffer>}
 */
export async function generateBuilderResumePdf({ resumeData, templateId = 'modern', customization = {} }) {
  if (!resumeData || typeof resumeData !== 'object') {
    throw new Error('Valid resume data is required to generate builder PDF.');
  }

  const { personalInfo = {}, education = [], experience = [], projects = [], skills = {}, additional = {} } = resumeData;
  const fullName = typeof personalInfo.fullName === 'string' && personalInfo.fullName.trim()
    ? personalInfo.fullName.trim()
    : 'Resume';

  const isAts = templateId === 'ats';
  const isProfessional = templateId === 'professional';

  // Accent color selection
  let primaryColor = '#111827';
  let accentColor = '#059669'; // Default Modern emerald

  if (isAts) {
    primaryColor = '#000000';
    accentColor = '#000000';
  } else if (isProfessional) {
    accentColor = customization.accentColor || '#1e293b';
    primaryColor = '#0f172a';
  } else if (customization.accentColor) {
    accentColor = customization.accentColor;
  }

  const bodyTextColor = isAts ? '#000000' : '#374151';
  const subtitleColor = isAts ? '#000000' : '#4b5563';

  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        margin: 40,
        size: 'A4',
        bufferPages: true,
        info: {
          Title: `${fullName} - Resume`,
          Author: fullName,
          Subject: `Generated via ResumeAI (${templateId} template)`,
        },
      });

      const chunks = [];
      doc.on('data', (c) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', (err) => reject(err));

      const fontRegular = isProfessional ? 'Times-Roman' : 'Helvetica';
      const fontBold = isProfessional ? 'Times-Bold' : 'Helvetica-Bold';
      const fontItalic = isProfessional ? 'Times-Italic' : 'Helvetica-Oblique';

      const leftMargin = doc.page.margins.left;
      const contentWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

      // 1. Header
      if (isProfessional || isAts) {
        doc.font(fontBold).fontSize(isAts ? 18 : 20).fillColor(primaryColor).text(fullName.toUpperCase(), { align: 'center' });
        if (personalInfo.headline) {
          doc.moveDown(0.2);
          doc.font(fontRegular).fontSize(10).fillColor(subtitleColor).text(personalInfo.headline, { align: 'center' });
        }
        const contactArr = [
          personalInfo.email,
          personalInfo.phone,
          personalInfo.location,
          personalInfo.linkedin,
          personalInfo.github,
          personalInfo.portfolio,
        ].filter(Boolean);
        if (contactArr.length > 0) {
          doc.moveDown(0.2);
          doc.font(fontRegular).fontSize(8.5).fillColor(bodyTextColor).text(contactArr.join('  |  '), { align: 'center' });
        }
        doc.moveDown(0.4);
        doc.strokeColor(isAts ? '#000000' : '#cbd5e1').lineWidth(isAts ? 1 : 1.5).moveTo(leftMargin, doc.y).lineTo(leftMargin + contentWidth, doc.y).stroke();
      } else {
        // Modern Header
        doc.font(fontBold).fontSize(20).fillColor(primaryColor).text(fullName.toUpperCase(), { align: 'left' });
        if (personalInfo.headline) {
          doc.moveDown(0.2);
          doc.font(fontBold).fontSize(10.5).fillColor(accentColor).text(personalInfo.headline);
        }
        const contactArr = [
          personalInfo.email,
          personalInfo.phone,
          personalInfo.location,
          personalInfo.linkedin,
          personalInfo.github,
        ].filter(Boolean);
        if (contactArr.length > 0) {
          doc.moveDown(0.2);
          doc.font(fontRegular).fontSize(8.5).fillColor(subtitleColor).text(contactArr.join('  •  '));
        }
        doc.moveDown(0.3);
        doc.strokeColor(accentColor).lineWidth(2).moveTo(leftMargin, doc.y).lineTo(leftMargin + contentWidth, doc.y).stroke();
      }

      doc.moveDown(0.4);

      // Section Header Helper
      const renderSectionHeading = (title) => {
        doc.moveDown(0.5);
        doc.font(fontBold).fontSize(10.5).fillColor(isAts ? '#000000' : accentColor).text(title.toUpperCase(), { lineGap: 2 });
        if (!isAts) {
          doc.strokeColor('#e2e8f0').lineWidth(0.75).moveTo(leftMargin, doc.y).lineTo(leftMargin + contentWidth, doc.y).stroke();
        } else {
          doc.strokeColor('#000000').lineWidth(0.5).moveTo(leftMargin, doc.y).lineTo(leftMargin + contentWidth, doc.y).stroke();
        }
        doc.moveDown(0.3);
      };

      // 2. Summary
      if (personalInfo.summary) {
        renderSectionHeading(isAts ? 'PROFESSIONAL SUMMARY' : 'Professional Summary');
        doc.font(fontRegular).fontSize(9).fillColor(bodyTextColor).text(personalInfo.summary, {
          lineGap: 2.5,
          align: 'justify',
        });
      }

      // 3. Technical Skills
      const hasSkills =
        skills.programmingLanguages ||
        skills.frameworks ||
        skills.databasesTools ||
        skills.softSkills ||
        additional.coursework;

      if (hasSkills) {
        renderSectionHeading(isAts ? 'AREAS OF EXPERTISE & TECHNICAL SKILLS' : 'Technical & Professional Skills');
        doc.font(fontRegular).fontSize(9).fillColor(bodyTextColor);
        if (skills.programmingLanguages) {
          doc.font(fontBold).text('Languages: ', { continued: true }).font(fontRegular).text(skills.programmingLanguages, { lineGap: 1.5 });
        }
        if (skills.frameworks) {
          doc.font(fontBold).text('Frameworks & Libraries: ', { continued: true }).font(fontRegular).text(skills.frameworks, { lineGap: 1.5 });
        }
        if (skills.databasesTools) {
          doc.font(fontBold).text('Databases & Developer Tools: ', { continued: true }).font(fontRegular).text(skills.databasesTools, { lineGap: 1.5 });
        }
        if (skills.softSkills) {
          doc.font(fontBold).text('Professional Strengths: ', { continued: true }).font(fontRegular).text(skills.softSkills, { lineGap: 1.5 });
        }
        if (additional.coursework) {
          doc.font(fontBold).text('Core Coursework: ', { continued: true }).font(fontRegular).text(additional.coursework, { lineGap: 1.5 });
        }
      }

      // 4. Experience
      const validExp = experience.filter((e) => e.jobTitle?.trim() || e.company?.trim());
      if (validExp.length > 0) {
        renderSectionHeading(isAts ? 'WORK EXPERIENCE' : 'Work Experience');
        validExp.forEach((exp) => {
          doc.font(fontBold).fontSize(9.5).fillColor(primaryColor).text(`${exp.jobTitle || 'Role'} — ${exp.company || 'Company'}`, { continued: true });
          const dateRange = `${exp.startDate || ''} – ${exp.current ? 'Present' : exp.endDate || ''}`;
          doc.font(fontItalic).fontSize(8.5).fillColor(subtitleColor).text(`  (${dateRange})`, { align: 'right' });

          if (exp.technologies) {
            doc.font(fontItalic).fontSize(8).fillColor(subtitleColor).text(`Technologies: ${exp.technologies}`, { lineGap: 1 });
          }

          if (exp.responsibilities) {
            const lines = exp.responsibilities.split('\n').filter(Boolean);
            lines.forEach((l) => {
              const clean = l.replace(/^[•\-*]\s*/, '');
              doc.font(fontRegular).fontSize(8.5).fillColor(bodyTextColor).text(`•  ${clean}`, { indent: 8, lineGap: 1.5 });
            });
          }

          if (exp.achievements) {
            doc.font(fontBold).fontSize(8.5).fillColor(primaryColor).text('★ Impact: ', { indent: 8, continued: true }).font(fontRegular).text(exp.achievements, { lineGap: 1.5 });
          }
          doc.moveDown(0.3);
        });
      }

      // 5. Projects
      const validProj = projects.filter((p) => p.title?.trim());
      if (validProj.length > 0) {
        renderSectionHeading(isAts ? 'KEY PROJECTS' : 'Technical Projects');
        validProj.forEach((p) => {
          doc.font(fontBold).fontSize(9.5).fillColor(primaryColor).text(p.title || 'Project', { continued: Boolean(p.technologies) });
          if (p.technologies) {
            doc.font(fontRegular).fontSize(8.5).fillColor(subtitleColor).text(` | ${p.technologies}`);
          }

          if (p.problemSolved) {
            doc.font(fontItalic).fontSize(8).fillColor(subtitleColor).text(`Problem Solved: ${p.problemSolved}`, { indent: 6 });
          }

          if (p.description) {
            doc.font(fontRegular).fontSize(8.5).fillColor(bodyTextColor).text(p.description, { indent: 6, lineGap: 1 });
          }

          if (p.contributions) {
            const lines = p.contributions.split('\n').filter(Boolean);
            lines.forEach((l) => {
              const clean = l.replace(/^[•\-*]\s*/, '');
              doc.font(fontRegular).fontSize(8.5).fillColor(bodyTextColor).text(`•  ${clean}`, { indent: 12, lineGap: 1 });
            });
          }

          if (p.results) {
            doc.font(fontBold).fontSize(8.5).fillColor(primaryColor).text('★ ', { indent: 6, continued: true }).font(fontRegular).text(p.results, { lineGap: 1.5 });
          }
          doc.moveDown(0.25);
        });
      }

      // 6. Education
      const validEdu = education.filter((e) => e.degree?.trim() || e.institution?.trim());
      if (validEdu.length > 0) {
        renderSectionHeading(isAts ? 'EDUCATION' : 'Education');
        validEdu.forEach((edu) => {
          doc.font(fontBold).fontSize(9).fillColor(primaryColor).text(`${edu.degree || 'Degree'}${edu.fieldOfStudy ? `, ${edu.fieldOfStudy}` : ''}`, { continued: true });
          const dateRange = `${edu.startDate || ''} – ${edu.current ? 'Present' : edu.endDate || ''}`;
          doc.font(fontItalic).fontSize(8.5).fillColor(subtitleColor).text(`  (${dateRange})`, { align: 'right' });

          doc.font(fontRegular).fontSize(8.5).fillColor(bodyTextColor).text(edu.institution || '', { continued: Boolean(edu.grade) });
          if (edu.grade) {
            doc.font(fontBold).fontSize(8).fillColor(primaryColor).text(` | Grade: ${edu.grade}`);
          }
          if (edu.coursework) {
            doc.font(fontItalic).fontSize(8).fillColor(subtitleColor).text(`Coursework: ${edu.coursework}`, { indent: 6 });
          }
          doc.moveDown(0.25);
        });
      }

      // 7. Additional Sections
      const hasExtra =
        (additional.certifications?.length || 0) > 0 ||
        (additional.publications?.length || 0) > 0 ||
        (additional.achievements?.length || 0) > 0 ||
        (additional.codingProfiles?.length || 0) > 0 ||
        (additional.languages?.length || 0) > 0;

      if (hasExtra) {
        renderSectionHeading(isAts ? 'CERTIFICATIONS & HONORS' : 'Certifications & Honors');
        doc.font(fontRegular).fontSize(8.5).fillColor(bodyTextColor);

        additional.certifications?.forEach((c) => {
          doc.font(fontBold).text('• ', { indent: 6, continued: true }).text(`${c.name || ''}`, { continued: true }).font(fontRegular).text(` — ${c.issuer || ''} ${c.issueDate ? `(${c.issueDate})` : ''}`, { lineGap: 1 });
        });

        additional.publications?.forEach((pub) => {
          doc.font(fontBold).text('• ', { indent: 6, continued: true }).text(`${pub.title || ''}`, { continued: true }).font(fontRegular).text(` — ${pub.publisher || ''} ${pub.date ? `(${pub.date})` : ''}`, { lineGap: 1 });
        });

        additional.achievements?.forEach((ach) => {
          doc.font(fontBold).text('• ', { indent: 6, continued: true }).text(`${ach.title || ''}`, { continued: true }).font(fontRegular).text(`: ${ach.description || ''}`, { lineGap: 1 });
        });

        additional.codingProfiles?.forEach((cp) => {
          doc.font(fontBold).text('• ', { indent: 6, continued: true }).text(`${cp.platform || ''}`, { continued: true }).font(fontRegular).text(`: ${cp.highlight || cp.username || ''}`, { lineGap: 1 });
        });

        if (additional.languages?.length > 0) {
          const langs = additional.languages.map((l) => `${l.language} (${l.proficiency})`).join(', ');
          doc.font(fontBold).text('• Languages: ', { indent: 6, continued: true }).font(fontRegular).text(langs, { lineGap: 1 });
        }
      }

      // 8. Footer page numbers
      const range = doc.bufferedPageRange();
      if (range.count > 1) {
        for (let i = 0; i < range.count; i++) {
          doc.switchToPage(i);
          doc
            .font(fontRegular)
            .fontSize(8)
            .fillColor('#94a3b8')
            .text(
              `${fullName}  |  Page ${i + 1} of ${range.count}`,
              leftMargin,
              doc.page.height - 25,
              { align: 'center', width: contentWidth }
            );
        }
      }

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}
